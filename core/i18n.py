def server_text(lang: str) -> dict:
    return SERVER_I18N.get(lang, SERVER_I18N["en"])


def language_from_code(code: str | None) -> str | None:
    """Return normalized language code if supported, else None."""
    if not code:
        return None
    normalized = code.strip().lower().split("-")[0]
    return normalized if normalized in SUPPORTED_LANGS else None


def language_from_header(accept_language: str) -> str:
    """Parse Accept-Language header and return the best supported language code."""
    if not accept_language:
        return "en"
    for part in accept_language.split(","):
        lang = part.strip().split(";")[0].strip().lower().split("-")[0]
        if lang in SUPPORTED_LANGS:
            return lang
    return "en"
